BEGIN;

DROP VIEW IF EXISTS v_student_attendance_summary;
DROP VIEW IF EXISTS v_attendance_detail;
DROP TABLE IF EXISTS audit_log CASCADE;
DROP TABLE IF EXISTS attendance_records CASCADE;
DROP TABLE IF EXISTS students CASCADE;
DROP TABLE IF EXISTS classes CASCADE;
DROP TABLE IF EXISTS staffs CASCADE;

-- ------------------------------------------------------------
-- STAFFS
-- ------------------------------------------------------------
CREATE TABLE staffs (
  staff_id  INTEGER GENERATED BY DEFAULT AS IDENTITY,
  s_name    VARCHAR(100) NOT NULL,
  password  VARCHAR(255) NOT NULL,
  ph_no     VARCHAR(20),
  emailid   VARCHAR(150) NOT NULL,
  PRIMARY KEY (staff_id),
  CONSTRAINT uq_staffs_emailid UNIQUE (emailid)
);

-- ------------------------------------------------------------
-- CLASSES
-- ------------------------------------------------------------
CREATE TABLE classes (
  class_id   INTEGER GENERATED BY DEFAULT AS IDENTITY,
  class_name VARCHAR(100) NOT NULL,
  class_pro  VARCHAR(100),
  room_no    VARCHAR(20),
  schedule   VARCHAR(100),
  staff_id   INTEGER,
  PRIMARY KEY (class_id),
  CONSTRAINT fk_classes_staff
    FOREIGN KEY (staff_id) REFERENCES staffs (staff_id)
    ON DELETE SET NULL
    ON UPDATE CASCADE
);

CREATE INDEX idx_classes_staff ON classes (staff_id);

-- ------------------------------------------------------------
-- STUDENTS
-- ------------------------------------------------------------
CREATE TABLE students (
  usn      VARCHAR(20) NOT NULL,
  s_name   VARCHAR(100) NOT NULL,
  stud_pw  VARCHAR(255) NOT NULL,
  sem      SMALLINT,
  ph_no    VARCHAR(20),
  emailid  VARCHAR(150) NOT NULL,
  PRIMARY KEY (usn),
  CONSTRAINT uq_students_emailid UNIQUE (emailid),
  CONSTRAINT chk_students_sem CHECK (sem IS NULL OR sem BETWEEN 1 AND 8)
);

-- ------------------------------------------------------------
-- ATTENDANCE_RECORDS
-- ------------------------------------------------------------
CREATE TABLE attendance_records (
  rec_id    BIGINT GENERATED BY DEFAULT AS IDENTITY,
  usn       VARCHAR(20) NOT NULL,
  class_id  INTEGER NOT NULL,
  staff_id  INTEGER,
  date      DATE NOT NULL,
  status    VARCHAR(20) NOT NULL DEFAULT 'Absent',
  "timestamp" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (rec_id),
  CONSTRAINT uq_attendance_student_class_date UNIQUE (usn, class_id, date),
  CONSTRAINT chk_attendance_status
    CHECK (status IN ('Present', 'Absent', 'Late', 'Excused')),
  CONSTRAINT fk_attendance_student
    FOREIGN KEY (usn) REFERENCES students (usn)
    ON DELETE CASCADE
    ON UPDATE CASCADE,
  CONSTRAINT fk_attendance_class
    FOREIGN KEY (class_id) REFERENCES classes (class_id)
    ON DELETE CASCADE
    ON UPDATE CASCADE,
  CONSTRAINT fk_attendance_staff
    FOREIGN KEY (staff_id) REFERENCES staffs (staff_id)
    ON DELETE SET NULL
    ON UPDATE CASCADE
);

CREATE INDEX idx_attendance_class_date ON attendance_records (class_id, date);
CREATE INDEX idx_attendance_staff ON attendance_records (staff_id);

-- ------------------------------------------------------------
-- AUDIT_LOG
-- ------------------------------------------------------------
CREATE TABLE audit_log (
  log_id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
  staff_id         INTEGER,
  action_type      VARCHAR(50) NOT NULL,
  action_timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (log_id),
  CONSTRAINT fk_audit_staff
    FOREIGN KEY (staff_id) REFERENCES staffs (staff_id)
    ON DELETE SET NULL
    ON UPDATE CASCADE
);

CREATE INDEX idx_audit_staff ON audit_log (staff_id);
CREATE INDEX idx_audit_timestamp ON audit_log (action_timestamp);

-- ------------------------------------------------------------
-- Trigger: keep the audit log in sync with attendance changes
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION log_attendance_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  v_staff_id INTEGER;
  v_rec_id   BIGINT;
BEGIN
  IF TG_OP = 'DELETE' THEN
    v_staff_id := OLD.staff_id;
    v_rec_id   := OLD.rec_id;
  ELSE
    v_staff_id := NEW.staff_id;
    v_rec_id   := NEW.rec_id;
  END IF;

  INSERT INTO audit_log (staff_id, action_type)
  VALUES (v_staff_id, CONCAT('ATTENDANCE_', TG_OP, ' rec_id=', v_rec_id));

  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_attendance_after_insert ON attendance_records;
CREATE TRIGGER trg_attendance_after_insert
AFTER INSERT ON attendance_records
FOR EACH ROW EXECUTE FUNCTION log_attendance_change();

DROP TRIGGER IF EXISTS trg_attendance_after_update ON attendance_records;
CREATE TRIGGER trg_attendance_after_update
AFTER UPDATE ON attendance_records
FOR EACH ROW EXECUTE FUNCTION log_attendance_change();

DROP TRIGGER IF EXISTS trg_attendance_after_delete ON attendance_records;
CREATE TRIGGER trg_attendance_after_delete
AFTER DELETE ON attendance_records
FOR EACH ROW EXECUTE FUNCTION log_attendance_change();

-- ------------------------------------------------------------
-- Views
-- ------------------------------------------------------------
CREATE VIEW v_attendance_detail AS
SELECT
  ar.rec_id,
  ar.date,
  ar.status,
  ar."timestamp" AS recorded_at,
  s.usn,
  s.s_name AS student_name,
  s.sem,
  c.class_id,
  c.class_name,
  c.class_pro,
  c.room_no,
  st.staff_id,
  st.s_name AS staff_name
FROM attendance_records ar
JOIN students s ON s.usn = ar.usn
JOIN classes c ON c.class_id = ar.class_id
LEFT JOIN staffs st ON st.staff_id = ar.staff_id;

CREATE VIEW v_student_attendance_summary AS
SELECT
  s.usn,
  s.s_name AS student_name,
  c.class_id,
  c.class_name,
  COUNT(*) AS total_classes,
  COUNT(*) FILTER (WHERE ar.status = 'Present') AS present_count,
  COUNT(*) FILTER (WHERE ar.status = 'Absent')  AS absent_count,
  COUNT(*) FILTER (WHERE ar.status = 'Late')    AS late_count,
  COUNT(*) FILTER (WHERE ar.status = 'Excused') AS excused_count,
  ROUND(
    COALESCE(
      COUNT(*) FILTER (WHERE ar.status IN ('Present', 'Late'))::numeric
        / NULLIF(COUNT(*), 0) * 100,
      0
    ),
    2
  ) AS attendance_percentage
FROM students s
JOIN attendance_records ar ON ar.usn = s.usn
JOIN classes c ON c.class_id = ar.class_id
GROUP BY s.usn, s.s_name, c.class_id, c.class_name;

